// The menu as it was before the admin panel existed. It's used to seed the
// database the first time, and as a fallback whenever the database isn't
// reachable (local dev without credentials, or an outage) so the site never
// shows an empty menu. Once the owner saves from /admin, the database copy wins.
const opt = (id, en, es = en, price = 0) => ({ id, label: { en, es }, price, active: true });

